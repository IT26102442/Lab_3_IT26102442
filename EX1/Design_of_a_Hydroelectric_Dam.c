#include <stdio.h>
int main (void)
{
	float power, height, work, flow_rate_of_water, n=0.9, m=1000, g=9.80;

	printf("Enter The Height Of The Dam (m) :");
        scanf("%f",&height);

        printf("Enter The Flow Rate Of Water (M/s) :");
	scanf("%f",&flow_rate_of_water);

	work = flow_rate_of_water*m*g*height;
	power = n*work;
	printf("Predicted Power Generated By The Hydroelectric Dam : %f MW",power/(1000000));

	return 0;

}

